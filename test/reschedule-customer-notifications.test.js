const assert = require('assert');
process.env.BOOKING_MANAGEMENT_SECRET = 'test-only';
const { buildDecisionMessages, notifyCustomerDecision, sendDecisionEmail } = require('../api/booking/_reschedule-customer-notifications');
const { decodeBookingManagementToken } = require('../api/booking/_manage');
const booking = { id: 'BK-NOTICE', client_name: 'Example Customer', email: 'customer@example.test', phone: '+15555550100', service_label: 'Deep Cleaning', schedule: '2030-01-05T14:00:00Z', estimate: { manHours: 6, rescheduling: { request: { id: 'request-test', status: 'approved', previousSchedule: '2030-01-02T14:00:00Z', feeCents: 2000 } } } };
(async () => {
  let message = buildDecisionMessages(booking);
  assert.match(message.text, /Work duration: 6 total work-hours/);
  assert.match(message.sms, /1 team member for up to 6 hours, or 2 team members for up to 3 hours/);
  assert.match(message.html, />Manage Your Appointment<\/a>/);
  assert.match(message.text, /\$20.00 \(10%\)/);
  assert.match(message.sms, /25% cancellation fee/);
  const claims = decodeBookingManagementToken(new URL(message.link).searchParams.get('token'));
  assert.equal(claims.bookingId, booking.id); assert.equal(claims.email, booking.email);
  assert(message.text.includes(message.link)); assert(message.sms.includes(message.link));
  booking.estimate.manHours = 7;
  booking.estimate.rescheduling.request.feeCents = 0;
  message = buildDecisionMessages(booking);
  assert.match(message.sms, /2 team members for up to 3 hours 30 minutes/);
  assert(!message.sms.includes('1 team member'));
  assert.match(message.text, /No rescheduling fee applies/);
  booking.estimate.rescheduling.request.status = 'declined';
  message = buildDecisionMessages(booking);
  assert.match(message.text, /original appointment remains confirmed/);
  assert.match(message.text, /January 2, 2030/);
  assert.match(message.text, /No rescheduling fee was charged/);
  booking.estimate.rescheduling.request.feeRefund = { amountCents: 2000, status: 'succeeded' };
  assert.match(buildDecisionMessages(booking).text, /\$20.00 rescheduling fee has been refunded/);
  booking.estimate.rescheduling.request.feeRefund.status = 'pending';
  assert.match(buildDecisionMessages(booking).text, /refund.*has been requested/);
  const delivery = await notifyCustomerDecision(booking, { email: async () => { throw new Error('email unavailable'); }, sms: async (phone, body) => { assert.equal(phone, booking.phone); assert.match(body, /Manage your appointment: https/); return { status: 'sent' }; } });
  assert.equal(delivery.email.status, 'error'); assert.equal(delivery.sms.status, 'sent');
  booking.estimate.rescheduling.customerNotifications = { declined: delivery };
  await notifyCustomerDecision(booking, { email: async () => ({ status: 'sent' }), sms: async () => { throw new Error('Successful SMS must not be sent again'); } });
  require('../api/quote/_shared').getGoogleClients = () => ({ gmail: { users: { messages: { send: async ({requestBody}) => { const raw = Buffer.from(requestBody.raw, 'base64url').toString(); assert.match(raw, /multipart\/alternative/); assert.match(raw, /To: customer@example.test/); assert.match(raw, /Work duration/); assert.match(raw, /Manage Your Appointment/); return { data: { id: 'test-email' } }; } } } } });
  assert.equal((await sendDecisionEmail(booking, buildDecisionMessages(booking))).status, 'sent');
  console.log('Customer approval/decline messages, duration, secure links, refund wording and independent delivery passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
