const assert = require("node:assert/strict");
const policy = require("../service-concern-policy");
const base = { "When concern first noticed": "Today at noon", "Type of concern": "Area was not cleaned" };
const image = { mimeType: "image/jpeg", size: 120 };
const video = { mimeType: "video/quicktime", size: 200 };
const pdf = { mimeType: "application/pdf", size: 100 };
const timing = { "Evidence timing": ["Before the cleaning", "Immediately after the cleaning"], "Photos taken before cleaning": "Yes" };
const reason = { "Evidence unavailable explanation": "I was not present and cannot access the property." };
assert.equal(policy.MAX_FILES, 10);
assert.match(policy.validate(base, []), /at least 2/);
assert.match(policy.validate(base, [image]), /at least 2/);
assert.match(policy.validate(base, [pdf, pdf]), /at least 2/);
assert.equal(policy.validate({ ...base, ...reason }, []), "");
assert.match(policy.validate({ ...base, "Evidence unavailable explanation": "  " }, []), /at least 2/);
assert.equal(policy.validate({ ...base, ...timing }, [image, image]), "");
assert.equal(policy.validate({ ...base, ...timing, ...reason }, [image]), "");
assert.match(policy.validate(base, [image, image]), /when the photos/);
assert.match(policy.validate({ ...base, "Evidence timing": "After the cleaning" }, [image, image]), /when the photos/);
assert.match(policy.validate({ ...base, "Evidence timing": "Before the cleaning" }, [image, image]), /whether any photos/);
assert.match(policy.validate(base, [video, video]), /at least 2/);
assert.equal(policy.validate({ ...base, ...reason, "Evidence timing": "Within 24 hours after the cleaning" }, [video]), "");
assert.match(policy.validate({ ...base, ...timing }, Array(11).fill(image)), /no more than 10/);
assert.equal(policy.validate({ ...base, ...timing }, Array(10).fill(image)), "");
assert.match(policy.validateFiles([{ mimeType: "text/html", size: 10 }]), /Please use/);
assert.match(policy.validateFiles([{ ...image, size: 21 * 1024 * 1024 }]), /20 MB/);
assert.match(policy.validateFiles([{ ...image, size: 0 }]), /20 MB/);
assert.equal(policy.fileType({ name: "camera.HEIC", type: "" }), "image/heic");
assert.equal(policy.fileType({ name: "clip.MOV", type: "" }), "video/quicktime");
assert.equal(policy.validate({ ...base, "Type of concern": "Cleaner arrived late" }, []), "");
assert.equal(policy.validate({ ...base, "Type of concern": "Health or safety concern" }, []), "");
const damage = { ...base, ...reason, "Type of concern": "Property was damaged", "Damaged item or surface": "Counter", "Damage discovered": "Today", "Condition before service": "Undamaged", "Item changes after damage": "No changes" };
assert.equal(policy.validate(damage, []), "");
assert.match(policy.validate({ ...damage, "Damaged item or surface": "" }, []), /Damaged item/);
assert.match(policy.validate({ ...damage, "Estimated repair or replacement cost": "-12" }, []), /valid non-negative/);
const missing = { ...base, "Type of concern": "Item is missing", "Missing item description": "Watch", "Last known location": "Dresser", "Item last seen": "Yesterday", "Other people with access": "Not sure", "Police report filed": "No" };
assert.equal(policy.validate(missing, []), "");
assert.match(policy.validate({ ...missing, "Item last seen": "" }, []), /Item last seen/);
const billing = { ...base, "Type of concern": "Incorrect charge or billing concern", "Amount disputed": "25.00", "Expected amount": "0", "Billing dispute reason": "Unexpected charge" };
assert.equal(policy.validate(billing, []), "");
assert.equal(policy.validate(billing, [pdf]), "");
assert.match(policy.validate({ ...billing, "Amount disputed": "25.001" }, []), /valid non-negative/);
assert.match(policy.validate({ ...billing, "Type of concern": ["Incorrect charge or billing concern", "Area was not cleaned"] }, []), /at least 2/);
const pruned = policy.relevantFields({ ...billing, "Damaged item or surface": "Stale answer", "Police report number": "Stale number", "Evidence timing": "Before the cleaning", "Photos taken before cleaning": "Yes" }, []);
assert.equal(pruned["Damaged item or surface"], undefined);
assert.equal(pruned["Police report number"], undefined);
assert.equal(pruned["Evidence timing"], undefined);
assert.equal(pruned["Photos taken before cleaning"], undefined);
assert.equal(pruned["Amount disputed"], "25.00");
console.log("Service concern policy tests passed: photo minimum, exception, file limits, timing, conditional details and stale-answer pruning.");
