const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {assertMinimumTotal} = require('../api/booking/_minimum-total');
for (const cents of [0,14999,NaN,Infinity]) assert.throws(()=>assertMinimumTotal(cents),/minimum booking total/);
for (const cents of [15000,15001]) assert.doesNotThrow(()=>assertMinimumTotal(cents));
const source=fs.readFileSync(require.resolve('../book-now.js'),'utf8');
let step=2, edits=0, focused=false;
const listeners={}, cancelButton={}, editButton={}, amount={}, shortfall={};
for (const button of [cancelButton,editButton]) button.addEventListener=(type,fn)=>button[type]=fn;
const dialog={open:false,querySelector:s=>s==='[data-minimum-current-total]'?amount:s==='[data-minimum-shortfall]'?shortfall:s==='[data-minimum-edit]'?editButton:cancelButton,showModal(){this.open=true;},close(){this.open=false;},addEventListener:(type,fn)=>listeners[type]=fn};
const state={package:{price:149.99}};
const context={state,Intl,Number,document:{querySelector:s=>s==='[data-minimum-dialog]'?dialog:s==='[data-load-availability]'?{focus(){focused=true;}}:{click(){edits++;}}},goToStep:n=>step=n};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  const minimumDialog ='),source.indexOf('  const availabilityButtons ='))+'\n globalThis.test={belowBookingMinimum,showBookingMinimum};',context);
assert(context.test.belowBookingMinimum());context.test.showBookingMinimum();assert(dialog.open);assert.equal(amount.textContent,'$149.99');assert.equal(shortfall.textContent,'$0.01');
cancelButton.click();assert(!dialog.open);assert.equal(step,2);assert(focused);assert.equal(state.package.price,149.99);
context.test.showBookingMinimum();editButton.click();assert.equal(edits,1);assert(!dialog.open);
context.test.showBookingMinimum();listeners.cancel({preventDefault(){}});assert(!dialog.open);assert.equal(step,2);
state.package.price=150;assert(!context.test.belowBookingMinimum());
state.package.price=142.50;assert(context.test.belowBookingMinimum(),'Discounted final total is checked');
console.log('Minimum popup: $150 boundary, edit, cancel, Escape, preserved quote and discounts passed.');
