const assert = require('node:assert/strict');
const {calculateResidentialQuoteBundle} = require('../api/booking/_shared');
const {applyRecurringDiscount} = require('../api/booking/_recurring-discount');
const unit = {bedrooms:1,fullBathrooms:1,halfBathrooms:0,kitchens:1,hasLivingRoom:'yes',hasDiningRoom:'no',livingDining:'living_only',hasPets:'no',refrigerator:'no',oven:'no',cabinets:'no',additionalCleaning:'no',windowCleaning:'no',additionalRooms:0};
const eligibility = {buildup:'none',clutter:'low',hazards:'none'};
const quote = changes => calculateResidentialQuoteBundle([{...unit,...changes}], 'recurring', eligibility);
const base = quote({});
const empty = quote({refrigerator:'empty',oven:'yes',cabinets:'yes',cabinetCount:2,drawerCount:1,cabinetsEmpty:'yes'});
const full = quote({refrigerator:'not-empty',oven:'yes',cabinets:'yes',cabinetCount:2,drawerCount:1,cabinetsEmpty:'no'});
assert.ok(empty.priceCents > base.priceCents);
assert.ok(full.priceCents > empty.priceCents);
assert.equal(empty.units[0].bedrooms,base.units[0].bedrooms);
assert.equal(empty.units[0].fullBathrooms,base.units[0].fullBathrooms);
assert.equal(empty.units[0].refrigerator,'empty');
assert.equal(full.units[0].cabinetsEmpty,'no');
assert.ok(full.teamHours >= base.teamHours);
const discounted = applyRecurringDiscount(full,{plan:'weekly',code:'WEEKLY20',percent:20});
assert.equal(discounted.priceCents, full.priceCents - Math.round(full.priceCents * 0.2));
assert.throws(()=>quote({cabinets:'yes',cabinetCount:0,drawerCount:0,cabinetsEmpty:'yes'}));
assert.equal(quote({}).priceCents,base.priceCents);
console.log('Recurring extras: empty/not-empty pricing, counts, duration, discount and preserved home details passed.');
